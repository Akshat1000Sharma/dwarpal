_RETRYABLE: frozenset[AgentAction] = frozenset({AgentAction.RETRY, AgentAction.WAIT})


def action_for(code: ReasonCode) -> AgentAction:
    return ACTIONS[code]


def is_retryable(code: ReasonCode) -> bool:
    return action_for(code) in _RETRYABLE


def is_approval(code: ReasonCode) -> bool:
    return code in APPROVAL_CODES
